// Captured with unmodified ac7187c, seed 287, C-319 profile and the benchmark's
// single Q-1 write. Covers every returned field AND array order, without timing
// assertions or any production records. Deliberately not regenerated by tests.
const BASELINE_SHA256 =
  "94e71388811fd10e5a618c03f0113874a900d1285560f68d8461348abea8fe5d";
test("production-size synthetic Needs You exactly matches the original reader response", async () => {
  const root = await mkdtemp(join(tmpdir(), "needs-golden-"));
  let store: Store | undefined;
  try {
    const data = join(root, "data");
    const manifest = await generateFixture({ out: data, profile: "needs-you" });
    for (const [table, minimum] of Object.entries({
      events: 42347,
      timeline: 18075,
      notifications: 8729,
      decisions: 590,
      cards: 318,
      runs: 5261,
    }))
      expect(manifest.tables[table].count).toBeGreaterThanOrEqual(minimum);
    store = Store.open({ dataDir: data });
    store.uow.run((tx) => {
      const q = tx.decisions.list(FIXTURE_PROJECT)[0];
      if (!q) throw new Error("missing decision");
      tx.decisions.put(FIXTURE_PROJECT, {
        ...q,
        context: `${q.context} updated`,
      });
    });
    const first = readNeedsState(store, FIXTURE_PROJECT);
    const response = JSON.stringify(needsYou(first, FIXTURE_NOW));
    expect(createHash("sha256").update(response).digest("hex")).toBe(
      BASELINE_SHA256,
    );
    expect(readNeedsState(store, FIXTURE_PROJECT)).toBe(first);
    expect(JSON.stringify(needsYou(first, FIXTURE_NOW))).toBe(response);
  } finally {
    store?.close();
    await rm(root, { recursive: true, force: true });
  }
}, 30000);

test("snapshots observe cross-connection changes, rollback, project isolation and restart", async () => {
  const root = await mkdtemp(join(tmpdir(), "needs-snapshots-"));
  const store = Store.open({ dataDir: root });
  let other: Store | undefined;
  try {
    seedWebProject(store, root);
    const empty = "needs-empty" as ProjectId;
    store.createProject({ id: empty });
    const first = readNeedsState(store, project_id);
    other = Store.open({ dataDir: root });
    const q = first.decisions[0];
    if (!q) throw new Error("missing decision");
    other.uow.run((tx) =>
      tx.decisions.put(project_id, { ...q, question: "New question" }),
    );
    const updated = readNeedsState(store, project_id);
    expect(updated.decisions.find((d) => d.id === q.id)?.question).toBe(
      "New question",
    );
    expect(updated.events).toBe(first.events);
    expect(first.decisions.find((d) => d.id === q.id)?.question).toBe(
      q.question,
    );
    expect(readNeedsState(store, empty).decisions).toEqual([]);
    expect(() =>
      other?.uow.run((tx) => {
        tx.decisions.put(project_id, { ...q, question: "Rolled back" });
        throw new Error("rollback");
      }),
    ).toThrow("rollback");
    expect(readNeedsState(store, project_id).decisions).toEqual(
      updated.decisions,
    );
    // Mutation invalidates cached source data; old snapshots remain immutable.
    const c = updated.cards[0];
    if (!c) throw new Error("missing card");
    other.uow.run((tx) => tx.cards.put(project_id, { ...c, sensitive: true }));
    expect(
      readNeedsState(store, project_id).cards.find((x) => x.id === c.id)
        ?.sensitive,
    ).toBe(true);
    other.uow.run((tx) =>
      tx.project_preferences.put(project_id, {
        id: project_id,
        auto_merge_after_minutes: null,
        pm_merge_confirmation: false,
      }),
    );
    const preferences = readNeedsState(store, project_id);
    expect(preferences.project_preferences?.[0]?.pm_merge_confirmation).toBe(
      false,
    );
    expect(updated.project_preferences?.[0]?.pm_merge_confirmation).not.toBe(
      false,
    );
    other.uow.run((tx) => {
      const owner = tx.members.list()[0];
      if (!owner) throw new Error("missing owner");
      tx.members.put({ ...owner, name: "Updated owner" });
      tx.decisions.put(project_id, {
        ...q,
        id: "Q-99" as typeof q.id,
        status: "open",
      });
    });
    const added = readNeedsState(store, project_id);
    expect(added.members?.[0]?.name).toBe("Updated owner");
    expect(
      needsYou(added, FIXTURE_NOW).decisions.some((x) => x.id === "Q-99"),
    ).toBe(true);
    other.uow.run((tx) =>
      tx.decisions.put(project_id, {
        ...q,
        id: "Q-99" as typeof q.id,
        status: "withdrawn",
      }),
    );
    expect(
      needsYou(readNeedsState(store, project_id), FIXTURE_NOW).decisions.some(
        (x) => x.id === "Q-99",
      ),
    ).toBe(false);
    other.uow.run((tx) =>
      tx.events.append(project_id, {
        id: tx.ids.nextEventId(),
        seq: tx.ids.nextEventSequence(project_id),
        type: "ext_message_failed",
        actor: { kind: "system", project_id },
        payload: { final: true },
        created_at: FIXTURE_NOW,
      }),
    );
    const appended = readNeedsState(store, project_id);
    expect(appended.events).not.toBe(added.events);
    expect(
      needsYou(appended, FIXTURE_NOW).notices.some(
        (n) => n.kind === "external_message",
      ),
    ).toBe(true);
    other.close();
    other = Store.open({ dataDir: root });
    expect(needsYou(readNeedsState(other, project_id), FIXTURE_NOW)).toEqual(
      needsYou(readNeedsState(store, project_id), FIXTURE_NOW),
    );
    // No cached view: elapsed time remains tied to the caller's clock.
    expect(
      needsYou(updated, "2026-01-03T00:00:00.000Z").decisions[0]?.waited_ms,
    ).not.toBe(
      needsYou(updated, "2026-01-02T00:00:00.000Z").decisions[0]?.waited_ms,
    );
  } finally {
    other?.close();
    store.close();
    await rm(root, { recursive: true, force: true });
  }
});

test("sharing scopes require live sessions and rotate after login; they authorize no request", async () => {
  const h = await webHarness({ password: "needs-scope-test-password" });
  try {
    const firstCookie = await h.login("needs-scope-test-password");
    const secondCookie = await h.login("needs-scope-test-password");
    const get = async (cookie?: string) => {
      const response = await fetch(`${h.server.url}/api/session`, {
        headers: cookie ? { cookie } : {},
      });
      return response.json() as Promise<{
        authenticated: boolean;
        read_scope?: string;
      }>;
    };
    const first = await get(firstCookie);
    expect(first.read_scope).toMatch(/^[a-f0-9]{64}$/u);
    expect((await get(secondCookie)).read_scope).not.toBe(first.read_scope);
    expect((await get(firstCookie)).read_scope).toBe(first.read_scope);
    expect((await get()).read_scope).toBeUndefined();
    h.store.revokeWebSession(firstCookie.split("=")[1] ?? "");
    expect((await get(firstCookie)).read_scope).toBeUndefined();
    const denied = await fetch(
      `${h.server.url}/api/projects/${project_id}/needs-you`,
      {
        headers: { authorization: `Bearer ${first.read_scope}` },
      },
    );
    expect(denied.status).toBe(401);
  } finally {
    await h.close();
  }
});
