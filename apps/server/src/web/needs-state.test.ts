// Flow Lite projection baseline: seed 287, C-319 profile and the benchmark's
// single Q-1 write. Covers every returned field AND array order, without timing
// assertions or any production records. Deliberately not regenerated by tests.
const BASELINE_SHA256 =
  "19e9ed5fbd5c281b0b9b59af645e83d0285eac23a10af7dafa7bc3c695b12a22";
// C-312 adds an event-derived notice source. Keep the existing digest for every
// original field/order; source classification has its own event contract tests.
// C-540 adds attachment thumbnail paths; they derive from the download path.
// C-503 adds story proposals; the synthetic data has none (asserted below).
// C-742 adds the human action executor; it is stripped below.
// C-750 adds cards waiting for the owner to mark done; the synthetic data has
// none (asserted below).
function legacyProjection(view: ReturnType<typeof needsYou>) {
  const {
    auto_merge_pause: _pause,
    story_proposals: _proposals,
    cards_to_close: _toClose,
    ...legacy
  } = view;
  return JSON.parse(
    JSON.stringify(
      {
        ...legacy,
        notices: legacy.notices.map(({ source: _source, ...notice }) => notice),
        // C-742 adds each action's executor after the golden response.
        human_actions: legacy.human_actions.map(
          ({ executor: _executor, ...action }) => action,
        ),
      },
      // C-540 thumbnails and C-614 previews postdate the golden response.
      (key, value) =>
        key === "thumbnail_path" || key === "preview_path" ? undefined : value,
    ),
  );
}
test("production-size synthetic Needs You exactly matches the original reader response", async () => {
  const root = await mkdtemp(join(tmpdir(), "needs-golden-"));
  let store: Store | undefined;
  try {
    const data = join(root, "data");
    const manifest = await generateFixture({ out: data, profile: "needs-you" });
    for (const [table, minimum] of Object.entries({
      events: 42347,
      timeline: 18075,
      notifications: 8729,
      decisions: 590,
      cards: 318,
      runs: 5261,
    }))
      expect(manifest.tables[table].count).toBeGreaterThanOrEqual(minimum);
    store = Store.open({ dataDir: data });
    store.uow.run((tx) => {
      const q = tx.decisions.list(FIXTURE_PROJECT)[0];
      if (!q) throw new Error("missing decision");
      tx.decisions.put(FIXTURE_PROJECT, {
        ...q,
        context: `${q.context} updated`,
      });
    });
    const first = readNeedsState(store, FIXTURE_PROJECT);
    const view = needsYou(first, FIXTURE_NOW);
    expect(view.auto_merge_pause).toEqual({ paused: false, waiting_count: 0 });
    expect(view.story_proposals).toEqual([]);
    expect(view.cards_to_close).toEqual([]);
    const response = JSON.stringify(legacyProjection(view));
    expect(createHash("sha256").update(response).digest("hex")).toBe(
      BASELINE_SHA256,
    );
    expect(
      createHash("sha256")
        .update(
          JSON.stringify(
            legacyProjection(needsYou(first, FIXTURE_NOW, "enabled")),
          ),
        )
        .digest("hex"),
    ).toBe("1111ed770fd954f93250bbea033911d979a0884615d50759a0e596abdee07851");
    const reference = legacyReadNeedsState(store, FIXTURE_PROJECT);
    for (const gate of ["disabled", "enabled", "invalid"] as const)
      expect(needsYou(first, FIXTURE_NOW, gate)).toEqual(
        needsYou(reference, FIXTURE_NOW, gate),
      );
    // Exact reviewer repro: these decisions have equal blocking/elapsed fields.
    store.uow.run((tx) => {
      const card = tx.cards.get(FIXTURE_PROJECT, "C-2");
      if (!card) throw new Error("missing card");
      tx.cards.put(FIXTURE_PROJECT, {
        ...card,
        id: "C-319",
        source: { kind: "decision", decision_id: "Q-110" },
        related_cards: [],
      });
    });
    const ordered = readNeedsState(store, FIXTURE_PROJECT);
    const legacyOrdered = legacyReadNeedsState(store, FIXTURE_PROJECT);
    for (const gate of ["disabled", "enabled", "invalid"] as const) {
      const actual = needsYou(ordered, FIXTURE_NOW, gate);
      expect(actual).toEqual(needsYou(legacyOrdered, FIXTURE_NOW, gate));
      const ids = actual.decisions.map((q) => q.id);
      expect(ids.indexOf("Q-110")).toBeLessThan(ids.indexOf("Q-103"));
    }
    store.uow.run((tx) => {
      const card = tx.cards.get(FIXTURE_PROJECT, "C-319");
      const q = tx.decisions.get(FIXTURE_PROJECT, "Q-103");
      if (!card || !q) throw new Error("missing fixture dependency");
      tx.cards.put(FIXTURE_PROJECT, {
        ...card,
        id: "C-320",
        status: "done",
        source: { kind: "decision", decision_id: "Q-103" },
      });
      tx.cards.put(FIXTURE_PROJECT, { ...card, related_cards: ["C-320"] });
      const { card_id: _card, ...projectDecision } = q;
      tx.decisions.put(FIXTURE_PROJECT, {
        ...projectDecision,
        id: "Q-90001",
        affected_cards: [],
        affected_work_items: [],
        status: "open",
      });
    });
    for (const gate of ["disabled", "enabled", "invalid"] as const)
      expect(
        needsYou(readNeedsState(store, FIXTURE_PROJECT), FIXTURE_NOW, gate),
      ).toEqual(
        needsYou(
          legacyReadNeedsState(store, FIXTURE_PROJECT),
          FIXTURE_NOW,
          gate,
        ),
      );
    expect(readNeedsState(store, FIXTURE_PROJECT)).not.toBe(ordered);
    expect(JSON.stringify(legacyProjection(needsYou(first, FIXTURE_NOW)))).toBe(
      response,
    );
  } finally {
    store?.close();
    await rm(root, { recursive: true, force: true });
  }
}, 30000);

test("snapshots observe cross-connection changes, rollback, project isolation and restart", async () => {
  const root = await mkdtemp(join(tmpdir(), "needs-snapshots-"));
  const store = Store.open({ dataDir: root });
  let other: Store | undefined;
  try {
    seedWebProject(store, root);
    const empty = "needs-empty" as ProjectId;
    store.createProject({ id: empty });
    const first = readNeedsState(store, project_id);
    other = Store.open({ dataDir: root });
    const q = first.decisions[0];
    if (!q) throw new Error("missing decision");
    other.uow.run((tx) =>
      tx.decisions.put(project_id, { ...q, question: "New question" }),
    );
    const updated = readNeedsState(store, project_id);
    expect(updated.decisions.find((d) => d.id === q.id)?.question).toBe(
      "New question",
    );
    expect(updated.events).toBe(first.events);
    expect(first.decisions.find((d) => d.id === q.id)?.question).toBe(
      q.question,
    );
    expect(readNeedsState(store, empty).decisions).toEqual([]);
    expect(() =>
      other?.uow.run((tx) => {
        tx.decisions.put(project_id, { ...q, question: "Rolled back" });
        throw new Error("rollback");
      }),
    ).toThrow("rollback");
    expect(readNeedsState(store, project_id).decisions).toEqual(
      updated.decisions,
    );
    // Mutation invalidates cached source data; old snapshots remain immutable.
    const c = updated.cards[0];
    if (!c) throw new Error("missing card");
    other.uow.run((tx) => tx.cards.put(project_id, { ...c, sensitive: true }));
    expect(
      readNeedsState(store, project_id).cards.find((x) => x.id === c.id)
        ?.sensitive,
    ).toBe(true);
    other.uow.run((tx) =>
      tx.project_preferences.put(project_id, {
        id: project_id,
        auto_merge_after_minutes: null,
        pm_merge_confirmation: false,
      }),
    );
    const preferences = readNeedsState(store, project_id);
    expect(preferences.project_preferences?.[0]?.pm_merge_confirmation).toBe(
      false,
    );
    expect(updated.project_preferences?.[0]?.pm_merge_confirmation).not.toBe(
      false,
    );
    other.uow.run((tx) => {
      const owner = tx.members.list()[0];
      if (!owner) throw new Error("missing owner");
      tx.members.put({ ...owner, name: "Updated owner" });
      tx.decisions.put(project_id, {
        ...q,
        id: "Q-99" as typeof q.id,
        status: "open",
      });
    });
    const added = readNeedsState(store, project_id);
    expect(added.members?.[0]?.name).toBe("Updated owner");
    expect(
      needsYou(added, FIXTURE_NOW).decisions.some((x) => x.id === "Q-99"),
    ).toBe(true);
    other.uow.run((tx) =>
      tx.decisions.put(project_id, {
        ...q,
        id: "Q-99" as typeof q.id,
        status: "withdrawn",
      }),
    );
    expect(
      needsYou(readNeedsState(store, project_id), FIXTURE_NOW).decisions.some(
        (x) => x.id === "Q-99",
      ),
    ).toBe(false);
    other.uow.run((tx) =>
      tx.events.append(project_id, {
        id: tx.ids.nextEventId(),
        seq: tx.ids.nextEventSequence(project_id),
        type: "ext_message_failed",
        actor: { kind: "system", project_id },
        payload: { final: true },
        created_at: FIXTURE_NOW,
      }),
    );
    const appended = readNeedsState(store, project_id);
    expect(appended.events).not.toBe(added.events);
    expect(
      needsYou(appended, FIXTURE_NOW).notices.some(
        (n) => n.kind === "external_message",
      ),
    ).toBe(true);
    other.close();
    other = Store.open({ dataDir: root });
    expect(needsYou(readNeedsState(other, project_id), FIXTURE_NOW)).toEqual(
      needsYou(readNeedsState(store, project_id), FIXTURE_NOW),
    );
    // No cached view: elapsed time remains tied to the caller's clock.
    expect(
      needsYou(updated, "2026-01-03T00:00:00.000Z").decisions[0]?.waited_ms,
    ).not.toBe(
      needsYou(updated, "2026-01-02T00:00:00.000Z").decisions[0]?.waited_ms,
    );
  } finally {
    other?.close();
    store.close();
    await rm(root, { recursive: true, force: true });
  }
});

test("sharing scopes require live sessions and rotate after login; they authorize no request", async () => {
  const h = await webHarness({ password: "needs-scope-test-password" });
  try {
    const firstCookie = await h.login("needs-scope-test-password");
    const secondCookie = await h.login("needs-scope-test-password");
    const get = async (cookie?: string) => {
      const response = await fetch(`${h.server.url}/api/session`, {
        headers: cookie ? { cookie } : {},
      });
      return response.json() as Promise<{
        authenticated: boolean;
        read_scope?: string;
      }>;
    };
    const first = await get(firstCookie);
    expect(first.read_scope).toMatch(/^[a-f0-9]{64}$/u);
    expect((await get(secondCookie)).read_scope).not.toBe(first.read_scope);
    expect((await get(firstCookie)).read_scope).toBe(first.read_scope);
    expect((await get()).read_scope).toBeUndefined();
    h.store.revokeWebSession(firstCookie.split("=")[1] ?? "");
    expect((await get(firstCookie)).read_scope).toBeUndefined();
    const denied = await fetch(
      `${h.server.url}/api/projects/${project_id}/needs-you`,
      {
        headers: { authorization: `Bearer ${first.read_scope}` },
      },
    );
    expect(denied.status).toBe(401);
  } finally {
    await h.close();
  }
});

test("optional sensitive Needs You fixture is visible only in its project snapshot", async () => {
  const root = await mkdtemp(join(tmpdir(), "needs-sensitive-"));
  let store: Store | undefined;
  try {
    const manifest = await generateFixture({
      out: join(root, "data"),
      profile: "small",
      sensitiveNeeds: true,
    });
    expect(manifest.scenarios.sensitive_needs).toBe("Q-90002");
    store = Store.open({ dataDir: join(root, "data") });
    const source = readNeedsState(store, FIXTURE_PROJECT);
    expect(source.cards.find((c) => c.id === "C-14")?.sensitive).toBe(true);
    expect(
      needsYou(source, FIXTURE_NOW, "enabled").decisions.find(
        (q) => q.id === "Q-90002",
      ),
    ).toMatchObject({
      card_id: "C-14",
      decider: "human",
      category: "permission",
    });
    expect(
      JSON.stringify(
        needsYou(
          readNeedsState(store, "synthetic-empty" as ProjectId),
          FIXTURE_NOW,
          "enabled",
        ),
      ),
    ).not.toContain("合成敏感");
  } finally {
    store?.close();
    await rm(root, { recursive: true, force: true });
  }
});
